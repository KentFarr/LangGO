import { strToU8, zipSync } from 'fflate';
import { describe, expect, it } from 'vitest';
import {
  decodeText,
  docxXmlToText,
  epubToText,
  extractTextFromFile,
  fileKind,
  htmlToText,
  stripSubtitles,
} from './extractors';

const fileOf = (name: string, content: Uint8Array | string, type = '') =>
  new File([typeof content === 'string' ? content : new Blob([content as BlobPart])], name, { type });

describe('fileKind', () => {
  it.each([
    ['book.EPUB', 'epub'],
    ['notes.txt', 'text'],
    ['episode.ja.vtt', 'subtitles'],
    ['movie.srt', 'subtitles'],
    ['essay.docx', 'docx'],
    ['page.html', 'html'],
    ['scan.pdf', 'pdf'],
    ['photo.png', null],
  ])('%s → %s', (name, kind) => {
    expect(fileKind(fileOf(name, ''))).toBe(kind);
  });
});

describe('decodeText', () => {
  it('reads UTF-8 and falls back to Shift_JIS', () => {
    expect(decodeText(strToU8('勉強'))).toBe('勉強');
    expect(decodeText(new Uint8Array([0x93, 0xfa, 0x96, 0x7b]))).toBe('日本');
  });
});

describe('stripSubtitles', () => {
  it('removes SRT numbering and timestamps', () => {
    const srt = '1\r\n00:00:01,000 --> 00:00:02,500\r\n今日は学校へ行きます。\r\n\r\n2\r\n00:00:03,000 --> 00:00:04,000\r\n<i>先生</i>に会いました。\r\n';
    expect(stripSubtitles(srt)).toBe('今日は学校へ行きます。\n先生に会いました。');
  });

  it('removes the WebVTT header, notes and cue settings', () => {
    const vtt = 'WEBVTT\n\nNOTE generated by YouTube\n\n00:00.000 --> 00:01.000 align:start\n<c>環境</c>の話\n';
    expect(stripSubtitles(vtt)).toBe('環境の話');
  });
});

describe('htmlToText', () => {
  it('drops scripts and furigana but keeps paragraph breaks', () => {
    const html =
      '<p><ruby>勉強<rt>べんきょう</rt></ruby>する</p><p>学校</p><script>var x = "広告"</script>';
    expect(htmlToText(html)).toBe('勉強する\n学校');
  });
});

describe('docxXmlToText', () => {
  it('joins runs within a paragraph and separates paragraphs', () => {
    const xml = `<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body>
      <w:p><w:r><w:t>環境</w:t></w:r><w:r><w:t>問題</w:t></w:r></w:p>
      <w:p><w:r><w:t>約束</w:t></w:r></w:p></w:body></w:document>`;
    expect(docxXmlToText(xml)).toBe('環境問題\n約束');
  });
});

function fakeEpub() {
  return {
    'META-INF/container.xml': strToU8(
      '<container><rootfiles><rootfile full-path="OEBPS/content.opf"/></rootfiles></container>',
    ),
    'OEBPS/content.opf': strToU8(`<package><manifest>
        <item id="c2" href="text/ch2.xhtml"/><item id="c1" href="text/ch1.xhtml"/>
      </manifest><spine><itemref idref="c1"/><itemref idref="c2"/></spine></package>`),
    'OEBPS/text/ch1.xhtml': strToU8(
      '<html xmlns="http://www.w3.org/1999/xhtml"><body><p>第一章：<ruby>世界<rt>せかい</rt></ruby></p></body></html>',
    ),
    'OEBPS/text/ch2.xhtml': strToU8('<html xmlns="http://www.w3.org/1999/xhtml"><body><p>第二章：自然</p></body></html>'),
  };
}

describe('epubToText', () => {
  it('reads chapters in spine order, resolving paths relative to the OPF', () => {
    expect(epubToText(fakeEpub())).toBe('第一章：世界\n第二章：自然');
  });

  it('explains when the container is missing', () => {
    expect(() => epubToText({})).toThrow(/couldn't be read/);
  });
});

describe('extractTextFromFile', () => {
  it('reads EPUB and DOCX archives', async () => {
    expect(await extractTextFromFile(fileOf('book.epub', zipSync(fakeEpub())))).toContain('第二章');

    const docx = zipSync({
      'word/document.xml': strToU8(
        '<w:document xmlns:w="w"><w:body><w:p><w:r><w:t>把握</w:t></w:r></w:p></w:body></w:document>',
      ),
    });
    expect(await extractTextFromFile(fileOf('essay.docx', docx))).toBe('把握');
  });

  it('reads subtitles and plain text', async () => {
    expect(await extractTextFromFile(fileOf('a.srt', '1\n00:00:01,000 --> 00:00:02,000\n電車\n'))).toBe('電車');
    expect(await extractTextFromFile(fileOf('a.txt', '天気'))).toBe('天気');
  });

  it('rejects corrupt archives and unknown types', async () => {
    await expect(extractTextFromFile(fileOf('bad.epub', 'not a zip'))).rejects.toThrow(/couldn't be opened/);
    await expect(extractTextFromFile(fileOf('photo.png', 'x'))).rejects.toThrow(/Unsupported/);
  });
});
